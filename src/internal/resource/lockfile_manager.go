package resource

import (
	"fmt"
	"os"
	"path/filepath"
	"time"

	"buildy/pkg/util"

	"gopkg.in/yaml.v3"
)

// LockfileEntry represents a locked dependency
type LockfileEntry struct {
	// For git dependencies
	Git       string `yaml:"git,omitempty"`
	Ref       string `yaml:"ref,omitempty"`
	Commit    string `yaml:"commit,omitempty"`
	FetchedAt string `yaml:"fetched_at,omitempty"`

	// For URL dependencies
	URL      string `yaml:"url,omitempty"`
	Checksum string `yaml:"checksum,omitempty"`
}

// Lockfile represents the dependencies.lock file
type Lockfile struct {
	Version        int                      `yaml:"version"`
	Generated      string                   `yaml:"generated"`
	Platform       string                   `yaml:"platform"`
	Dependencies   map[string]LockfileEntry `yaml:"dependencies"`
	SystemWarnings []string                 `yaml:"system_warnings,omitempty"`
}

// LockfileManager manages lockfile generation and validation
type LockfileManager struct {
	lockfilePath string
	platform     string
	architecture string
}

// NewLockfileManager creates a new LockfileManager
func NewLockfileManager(workspaceRoot, platform, architecture string) *LockfileManager {
	return &LockfileManager{
		lockfilePath: filepath.Join(workspaceRoot, "buildy", "dependencies.lock"),
		platform:     platform,
		architecture: architecture,
	}
}

// Exists checks if a lockfile exists
func (lm *LockfileManager) Exists() bool {
	_, err := os.Stat(lm.lockfilePath)
	return err == nil
}

// Load loads an existing lockfile
func (lm *LockfileManager) Load() (*Lockfile, error) {
	data, err := os.ReadFile(lm.lockfilePath)
	if err != nil {
		return nil, fmt.Errorf("failed to read lockfile: %w", err)
	}

	var lockfile Lockfile
	if err := yaml.Unmarshal(data, &lockfile); err != nil {
		return nil, fmt.Errorf("failed to parse lockfile: %w", err)
	}

	return &lockfile, nil
}

// Generate generates a new lockfile from resolved dependencies
func (lm *LockfileManager) Generate(deps map[string]*ResolvedDependency, fetchManager *FetchManager, warnings []string) (*Lockfile, error) {
	lockfile := &Lockfile{
		Version:        1,
		Generated:      time.Now().UTC().Format(time.RFC3339),
		Platform:       fmt.Sprintf("%s-%s", lm.platform, lm.architecture),
		Dependencies:   make(map[string]LockfileEntry),
		SystemWarnings: warnings,
	}

	for name, dep := range deps {
		if dep.Type == DepTypeFetch {
			entry := LockfileEntry{
				FetchedAt: time.Now().UTC().Format(time.RFC3339),
			}

			// Handle git dependencies
			if dep.SourceGit != "" {
				entry.Git = dep.SourceGit
				entry.Ref = dep.SourceRef

				// Get current commit hash
				if dep.Path != "" {
					commit, err := fetchManager.GetGitCommit(dep.Path)
					if err == nil {
						entry.Commit = commit
					}
				}
			}

			// Handle URL dependencies
			if dep.SourceURL != "" {
				entry.URL = dep.SourceURL

				// Get SHA256 from download metadata
				metadata, err := fetchManager.GetDownloadMetadata(dep.SourceURL)
				if err == nil && metadata.SHA256 != "" {
					entry.Checksum = "sha256:" + metadata.SHA256
				} else {
					util.LogWarning("Could not get checksum for '%s' - lockfile may not be fully reproducible", name)
				}
			}

			lockfile.Dependencies[name] = entry
		}
	}

	return lockfile, nil
}

// Save saves the lockfile to disk
func (lm *LockfileManager) Save(lockfile *Lockfile) error {
	// Ensure directory exists
	dir := filepath.Dir(lm.lockfilePath)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("failed to create lockfile directory: %w", err)
	}

	data, err := yaml.Marshal(lockfile)
	if err != nil {
		return fmt.Errorf("failed to marshal lockfile: %w", err)
	}

	// Add header comment
	header := "# Buildy dependencies lockfile - DO NOT EDIT\n# Generated by buildy --update-lock\n# This file ensures reproducible builds by pinning exact dependency versions\n\n"
	content := header + string(data)

	if err := os.WriteFile(lm.lockfilePath, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write lockfile: %w", err)
	}

	util.LogInfo("Generated lockfile: %s", lm.lockfilePath)
	return nil
}

// Validate validates that current dependencies match the lockfile
func (lm *LockfileManager) Validate(deps map[string]*ResolvedDependency, fetchManager *FetchManager) error {
	lockfile, err := lm.Load()
	if err != nil {
		return err
	}

	for name, lockedEntry := range lockfile.Dependencies {
		dep, ok := deps[name]
		if !ok {
			util.LogWarning("Locked dependency '%s' not found in current config", name)
			continue
		}

		if dep.Type != DepTypeFetch {
			continue
		}

		// Validate git dependencies by commit hash
		if lockedEntry.Commit != "" && dep.Path != "" {
			currentCommit, err := fetchManager.GetGitCommit(dep.Path)
			if err != nil {
				return fmt.Errorf("failed to get commit for %s: %w", name, err)
			}

			if currentCommit != lockedEntry.Commit {
				return fmt.Errorf(
					"dependency '%s' commit mismatch:\n  locked:  %s\n  current: %s\n\nRun 'buildy --update-lock' to update the lockfile",
					name, lockedEntry.Commit, currentCommit,
				)
			}
		}

		// Validate URL dependencies by checksum
		if lockedEntry.URL != "" && lockedEntry.Checksum != "" {
			metadata, err := fetchManager.GetDownloadMetadata(lockedEntry.URL)
			if err != nil {
				util.LogWarning("Could not verify checksum for '%s': no metadata found", name)
				continue
			}

			// Compare checksums (lockfile stores "sha256:hash", metadata stores just hash)
			lockedHash := lockedEntry.Checksum
			if len(lockedHash) > 7 && lockedHash[:7] == "sha256:" {
				lockedHash = lockedHash[7:]
			}

			if metadata.SHA256 != lockedHash {
				return fmt.Errorf(
					"dependency '%s' checksum mismatch:\n  locked:  %s\n  current: %s\n\nRun 'buildy --update-lock' to update the lockfile",
					name, lockedEntry.Checksum, "sha256:"+metadata.SHA256,
				)
			}
		}
	}

	util.LogInfo("Lockfile validation passed")
	return nil
}

// Update updates the lockfile with current dependency state
func (lm *LockfileManager) Update(deps map[string]*ResolvedDependency, fetchManager *FetchManager, warnings []string) error {
	lockfile, err := lm.Generate(deps, fetchManager, warnings)
	if err != nil {
		return err
	}
	return lm.Save(lockfile)
}

// GetPath returns the lockfile path
func (lm *LockfileManager) GetPath() string {
	return lm.lockfilePath
}
